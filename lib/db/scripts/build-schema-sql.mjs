// Regenerates src/schema-sql.ts: the whole Drizzle schema as statements that
// are safe to run on every start. Tables, columns, constraints and indexes are
// only created when missing; nothing is ever dropped or altered.
//
//   pnpm --filter @workspace/db run schema-sql
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const tmp = path.join(root, ".schema-sql-tmp");
fs.rmSync(tmp, { recursive: true, force: true });
execFileSync(process.execPath, ["./node_modules/drizzle-kit/bin.cjs", "generate", "--config", "./scripts/schema-sql.config.ts", "--name", "full"], {
  cwd: root,
  stdio: "ignore",
});
const file = fs.readdirSync(tmp).find((f) => f.endsWith(".sql"));
const raw = fs.readFileSync(path.join(tmp, file), "utf8");
fs.rmSync(tmp, { recursive: true, force: true });

const statements = raw.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean);
const tables = [];
const out = [];
const guarded = (sql) => `DO $$ BEGIN ${sql} EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL; END $$;`;

for (const statement of statements) {
  const create = statement.match(/^CREATE TABLE "([^"]+)" \(\n([\s\S]*)\n\);$/);
  if (create) {
    const [, table, body] = create;
    tables.push(table);
    out.push(statement.replace(/^CREATE TABLE "/, 'CREATE TABLE IF NOT EXISTS "'));
    // Columns added since a table was first created. A NOT NULL column with no
    // default can't be added to a table that has rows, and every such column
    // predates this step, so those are left alone.
    for (const line of body.split("\n").map((l) => l.trim().replace(/,$/, ""))) {
      if (line.startsWith("CONSTRAINT")) {
        out.push(guarded(`ALTER TABLE "${table}" ADD ${line};`));
        continue;
      }
      const column = line.match(/^"([^"]+)" (.+)$/);
      if (!column || /PRIMARY KEY/.test(column[2])) continue;
      if (/NOT NULL/.test(column[2]) && !/DEFAULT/.test(column[2])) continue;
      out.push(`ALTER TABLE "${table}" ADD COLUMN IF NOT EXISTS "${column[1]}" ${column[2]};`);
    }
    continue;
  }
  if (/^ALTER TABLE .* ADD CONSTRAINT/.test(statement)) {
    out.push(guarded(statement));
    continue;
  }
  if (/^ALTER TABLE "[^"]+" ENABLE ROW LEVEL SECURITY;$/.test(statement)) {
    out.push(statement); // already safe to repeat
    continue;
  }
  if (/^CREATE (UNIQUE )?INDEX "/.test(statement)) {
    out.push(statement.replace(/^CREATE (UNIQUE )?INDEX "/, (m, u) => `CREATE ${u ?? ""}INDEX IF NOT EXISTS "`));
    continue;
  }
  throw new Error(`Don't know how to make this idempotent:\n${statement}`);
}

const ts = `// Generated by scripts/build-schema-sql.mjs from src/schema. Do not edit by hand:
// change the schema, then run \`pnpm --filter @workspace/db run schema-sql\`.

/** Every ScopeCI table, for turning on row level security. */
export const SCHEMA_TABLES: string[] = ${JSON.stringify(tables, null, 2)};

/** The whole schema, as statements that only create what is missing. */
export const SCHEMA_STATEMENTS: string[] = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, "src", "schema-sql.ts"), ts);
console.log(`Wrote ${out.length} statements for ${tables.length} tables.`);
